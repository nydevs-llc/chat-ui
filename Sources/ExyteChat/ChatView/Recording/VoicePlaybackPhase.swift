//  VoicePlaybackPhase.swift
//
//  Фаза кнопки play у голосового: что рисовать — треугольник, паузу, спиннер.
//

import Foundation

/// Что показывает кнопка воспроизведения прямо сейчас.
///
/// Отдельный тип, а не набор булевых условий во вьюхе, ровно по одной причине:
/// **состояния «ещё не начали» и «уже доиграли» внешне неразличимы**. У плеера
/// в обоих случаях `playing == false, progress == 0` — `handlePlaybackReachedEnd`
/// перематывает трек в ноль, чтобы его можно было послушать снова.
///
/// Пока «идёт загрузка» выводилась из этой пары, спиннер неизбежно возвращался
/// после конца трека и висел до срабатывания предохранителя. Это был не промах в
/// условии, а следствие того, что загрузку выводили из полей, описывающих
/// воспроизведение. Здесь фаза хранится явно и меняется только по событиям.
enum VoicePlaybackPhase: Equatable {

    /// Файл ещё не запрашивали. Рисуем треугольник.
    case idle

    /// Трек доигран до конца. Рисуем треугольник — внешне неотличимо от `idle`.
    ///
    /// Отдельный кейс, а не `idle`, ровно по той же причине, по которой этот тип
    /// вообще появился: «доиграли» и «не начинали» обязаны по-разному отвечать на
    /// намерение из приложения. Намерение (`pendingVoiceMessagePlays`) гасится
    /// только в `trackVoiceMessagePlayed`, а тот дедуплицирован — один раз на
    /// `file_id` за показ экрана. Значит после первого прослушивания оно может
    /// остаться поднятым: ошибка резолва разошлась с воспроизведением, гонка при
    /// переотдаче сообщения. Читай мы его из `idle` — спиннер вернулся бы на
    /// доигранном треке и крутился до предохранителя, то есть ровно исходный баг.
    ///
    /// Из `finished` намерение игнорируется: пользователь уже услышал запись,
    /// намерение по смыслу отработано, и новый запрос доказывается только тапом.
    case finished

    /// Пользователь нажал play, звука ещё нет: резолвим ссылку, качаем, декодируем.
    /// Рисуем спиннер.
    case buffering

    /// Playhead поехал — звук слышно. Рисуем паузу.
    case playing

    /// Пользователь поставил на паузу сам. Рисуем треугольник.
    ///
    /// Отдельно от `idle`, потому что пауза — это середина трека, а `idle` — его
    /// начало. Внешне кнопка одинакова, но следующий тап означает разное
    /// («продолжить» против «начать»), и склеивать их — снова терять различие,
    /// с которого начался баг.
    case paused

    /// Спиннер крутится, но звук так и не пошёл — сдались по таймауту и вернули
    /// треугольник, чтобы можно было ткнуть ещё раз.
    ///
    /// Не `idle`: намерение в приложении может быть ещё живо, и опоздавший файл
    /// доиграет сам. Гасим ровно картинку, ничего больше.
    case gaveUp

    /// Крутить ли спиннер вместо иконки.
    var showsSpinner: Bool { self == .buffering }

    /// Показывать паузу (иначе — треугольник).
    var showsPauseIcon: Bool { self == .playing }
}

/// События, которые двигают фазу. Ровно то, что вьюха реально наблюдает.
enum VoicePlaybackEvent: Equatable {

    /// Тап по кнопке. `isResolved` — файл уже локально готов.
    case tapped(isResolved: Bool)

    /// Плеер сообщил, что playhead сдвинулся с нуля: звук физически идёт.
    case progressAdvanced

    /// Плеер поднял `playing`.
    case playerDidStart

    /// Плеер опустил `playing`, не дойдя до конца трека, — это пауза.
    case playerDidPause

    /// Трек доигран до конца (`didPlayTillEnd`).
    case reachedEnd

    /// Истёк предохранитель от вечного спиннера.
    case bufferingTimedOut

    /// Приложение сообщило, что намерение сыграть живо (переживает пересоздание
    /// строки). Нужно, чтобы новое поколение вьюхи родилось сразу со спиннером.
    case pendingIntentObserved

    /// Вьюха ушла с экрана.
    case disappeared
}

extension VoicePlaybackPhase {

    /// Единственное место, где меняется фаза.
    ///
    /// Переходы описаны явно и исчерпывающе: любое сочетание, которого здесь нет,
    /// фазу не меняет. Именно поэтому «доиграли» больше не может выглядеть как
    /// «грузимся» — `reachedEnd` ведёт в `finished`, откуда спиннер поднимает
    /// только явный тап: ни поздний нулевой `progress` от перемотки в начало, ни
    /// залипшее намерение из приложения туда не дотягиваются.
    func applying(_ event: VoicePlaybackEvent) -> VoicePlaybackPhase {
        switch event {

        case .tapped(let isResolved):
            switch self {
            case .playing:
                // Тап во время звука — пауза. Плеер подтвердит `playerDidPause`,
                // но фазу двигаем сразу: кнопка обязана откликаться мгновенно.
                return .paused
            case .idle, .finished, .paused, .gaveUp, .buffering:
                // Готовый файл стартует практически мгновенно, и спиннер на нём
                // успел бы только моргнуть — это выглядит как дефект, а не как
                // отзывчивость. Ждём `playerDidStart`.
                //
                // Неготовый — наоборот: впереди сеть и декод, ради этой паузы
                // спиннер и заводился.
                return isResolved ? self.startingResolved() : .buffering
            }

        case .progressAdvanced:
            // Звук идёт — единственное надёжное доказательство. Гасит и спиннер,
            // и защёлку сдачи: после `gaveUp` опоздавший файл доигрывает сам, и
            // кнопка обязана показать паузу, а не остаться треугольником.
            return .playing

        case .playerDidStart:
            // `playing` поднимается БЕЗ проверки статуса item'а: протухшая ссылка
            // даёт `playing == true` при полной тишине. Поэтому из буферизации
            // сам по себе он не выводит — ждём `progressAdvanced`.
            //
            // Из `idle`/`paused` он означает старт готового файла: показываем
            // паузу сразу, иначе кнопка на локальном файле «залипала» бы
            // треугольником до первого тика playhead.
            switch self {
            case .buffering, .gaveUp: return self
            case .idle, .finished, .paused, .playing: return .playing
            }

        case .playerDidPause:
            // Плеер опустил `playing` не по концу трека. Из буферизации не
            // выводим: там `playing` и не поднимался.
            switch self {
            case .playing: return .paused
            case .buffering, .gaveUp, .idle, .finished, .paused: return self
            }

        case .reachedEnd:
            // Ключевой переход, ради которого всё затевалось. Трек доигран —
            // фаза `finished`, и последующий `progress == 0` от перемотки в
            // начало уже никак не читается как «грузимся».
            return .finished

        case .bufferingTimedOut:
            return self == .buffering ? .gaveUp : self

        case .pendingIntentObserved:
            // Намерение живо, а звука ещё нет — новое поколение вьюхи после
            // переотдачи сообщения: собственный `@State` умер вместе со старым
            // поколением, но намерение живёт в приложении по `file_id`. Поднять
            // спиннер обязаны именно здесь, иначе тап до пересоздания строки
            // остался бы без видимого отклика.
            //
            // Слушаем его ТОЛЬКО из `idle`. Во всех прочих фазах намерение либо
            // уже отработано, либо не добавляет знания:
            //
            // - `finished` — пользователь запись услышал. Намерение могло
            //   остаться поднятым (гасится дедуплицированным
            //   `trackVoiceMessagePlayed`), и доверять ему здесь значило бы
            //   вернуть спиннер на доигранном треке — исходный баг. Новый запрос
            //   доказывается только тапом.
            // - `playing`/`paused` — звук уже был, намерение просто не успели
            //   погасить; гонка реальна, и вмешательство сломало бы иконку.
            // - `buffering`/`gaveUp` — спиннер и так учтён.
            switch self {
            case .idle: return .buffering
            case .finished, .buffering, .playing, .paused, .gaveUp: return self
            }

        case .disappeared:
            return .idle
        }
    }

    /// Тап по готовому файлу: спиннер не показываем, но и паузу рисовать рано —
    /// звук ещё не пошёл. Держим прежнюю фазу, её сменит `playerDidStart`.
    ///
    /// Исключение — `gaveUp`: защёлку сдачи снимаем, иначе она пережила бы новую
    /// попытку и запретила спиннер, если следующий тап случится уже по
    /// неготовому файлу.
    private func startingResolved() -> VoicePlaybackPhase {
        self == .gaveUp ? .idle : self
    }
}
