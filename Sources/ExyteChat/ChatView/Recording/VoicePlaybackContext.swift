import Foundation

/// Что сейчас происходит с воспроизведением и К КАКОЙ записи это относится.
///
/// Отдельный значимый тип, а не набор полей плеера, по одной причине: плеер в
/// переписке ОДИН на экран, а строк с голосовыми — много. Каждая строка обязана
/// уметь ответить «этот прогресс про меня?», и пока величины разрознены, ответ
/// приходится собирать во вьюхе. Переиспользованная ячейка при этом неизбежно
/// показывает чужой прогресс: она просто не знает, что данные сменились.
///
/// `matching(_:)` делает сброс на чужой контекст ЯВНОЙ веткой, а не побочным
/// эффектом пересоздания вьюхи (именно на этом побочном эффекте держалась
/// прежняя схема с плеером в `@StateObject` — и ломалась вместе с ним, когда
/// ячейку переконфигурировали во время звука).
///
/// `Equatable` здесь не удобство, а требование производительности: неиграющая
/// строка на каждом тике должна получать ОДНО И ТО ЖЕ значение, иначе SwiftUI
/// перерисовывает всю ленту 5-10 раз в секунду.
struct VoicePlaybackContext: Equatable {

    /// Локальный файл, который сейчас заряжен в плеер. `nil` — плеер простаивает.
    var assetURL: URL?

    /// Доля проигранного, 0...1. Заполняется периодическим наблюдателем времени.
    var progress: Double

    /// Сколько осталось до конца, в секундах. Показывается в подписи под волной.
    var secondsLeft: Double

    /// Плеер поднял флаг воспроизведения.
    ///
    /// - Important: сам по себе НЕ доказывает, что звук слышно —
    ///   `RecordingPlayer.play()` поднимает его без проверки статуса item'а.
    ///   Доказательство звука — `progress > 0`.
    var isPlaying: Bool

    /// Покой: ничего не заряжено, ничего не играет.
    static let notLoaded = VoicePlaybackContext(
        assetURL: nil,
        progress: 0,
        secondsLeft: 0,
        isPlaying: false
    )

    /// Контекст с точки зрения строки, показывающей запись по адресу `url`.
    ///
    /// Чужая запись (и отсутствие записи) — это `notLoaded`, а не «оставить как
    /// было»: строка обязана СБРОСИТЬСЯ, иначе после переиспользования ячейки на
    /// ней останется прогресс предыдущего сообщения.
    func matching(_ url: URL?) -> VoicePlaybackContext {
        guard let url, assetURL == url else { return .notLoaded }
        return self
    }
}
